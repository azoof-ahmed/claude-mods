"""Generated markdown view of the tracker (`task.py export`; never hand-edited)."""
from __future__ import annotations

from pathlib import Path
from typing import Optional

import taskdb as db

ORDER = ['in_progress', 'in_review', 'blocked', 'todo', 'backlog']


def _cell(s, n=90):
    s = (s or '').replace('|', '/').replace('\n', ' ')
    return s if len(s) <= n else s[:n - 1] + '…'


def write_board_md(conn, out: Optional[Path] = None) -> Path:
    out = out or db.cfg().db_path.with_name('TASKS_BOARD.md')
    by = dict(conn.execute('SELECT status, COUNT(*) FROM issues GROUP BY status').fetchall())
    lines = ['# Tasks board (generated by `task.py export`; do not edit, use the CLI)', '',
             f'Generated {db.now()}. ' + ', '.join(f'{s} {by.get(s, 0)}' for s in db.STATUSES), '']
    conflicts = db.all_conflicts(conn)
    if conflicts:
        lines += ['## File conflicts', ''] + [f'- {x["a"]} ({x["a_assignee"]}) x {x["b"]} ({x["b_assignee"]}): '
                                              f'`{x["a_glob"]}` / `{x["b_glob"]}`' for x in conflicts] + ['']
    areas = [r[0] for r in conn.execute("SELECT DISTINCT COALESCE(area,'(no area)') FROM issues "
                                        "WHERE status NOT IN ('done','cancelled') ORDER BY 1")]
    for area in areas:
        rows = conn.execute("SELECT * FROM issues WHERE COALESCE(area,'(no area)')=? AND status NOT IN "
                            "('done','cancelled')", (area,)).fetchall()
        rows.sort(key=lambda r: (ORDER.index(r['status']), db.PRIORITIES.index(r['priority']), r['id']))
        lines += [f'## {area} ({len(rows)} open)', '', '| id | status | prio | assignee | title |',
                  '|---|---|---|---|---|']
        lines += [f'| {db.fmt_key(r["id"])} | {r["status"]} | {r["priority"]} | {r["assignee"] or "-"} | '
                  f'{_cell(r["title"])} |' for r in rows] + ['']
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text('\n'.join(lines), encoding='utf-8')
    return out
